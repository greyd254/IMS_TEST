--            qua lại trên một sự cố (không chỉ 1 lần đánh giá như PHAN_HOI),
--            mỗi tin nhắn có thể kèm 1 file (ảnh, PDF, Word, TXT, ZIP).
--            THOI_GIAN dùng TIMESTAMP (có giờ phút giây) để sắp mới nhất lên trước.
--            Nếu dựng CSDL từ đầu bằng 00_run_all.sql thì đã có sẵn trong
--            02_tables.sql, không cần chạy file này.
