SET DEFINE OFF

CREATE TABLE BINH_LUAN_SU_CO (
  MA_BL         NUMBER GENERATED BY DEFAULT AS IDENTITY,
  MA_SC         NUMBER NOT NULL,
  MA_NGUOI_GUI  NUMBER NOT NULL,
  NOI_DUNG      VARCHAR2(1000 CHAR),
  TEP_DINH_KEM  VARCHAR2(500 CHAR),
  THOI_GIAN     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_BINH_LUAN_SU_CO PRIMARY KEY (MA_BL),
  CONSTRAINT FK_BINH_LUAN_SU_CO FOREIGN KEY (MA_SC) REFERENCES SU_CO (MA_SC),
  CONSTRAINT FK_BINH_LUAN_NGUOI FOREIGN KEY (MA_NGUOI_GUI) REFERENCES NGUOI_DUNG (MA_ND),
  CONSTRAINT CK_BINH_LUAN_CO_NOI_DUNG CHECK (NOI_DUNG IS NOT NULL OR TEP_DINH_KEM IS NOT NULL)
);
CREATE INDEX IDX_BINH_LUAN_SU_CO ON BINH_LUAN_SU_CO (MA_SC);
CREATE INDEX IDX_BINH_LUAN_NGUOI ON BINH_LUAN_SU_CO (MA_NGUOI_GUI);

-- Dữ liệu mẫu nhẹ: 1 tin nhắn demo cho tối đa 2 sự cố đang có (không dùng ID cố định)
INSERT INTO BINH_LUAN_SU_CO (MA_SC, MA_NGUOI_GUI, NOI_DUNG)
SELECT sc.MA_SC, sc.MA_NGUOI_BAO, 'Khi nào thì xử lý xong ạ?'
  FROM SU_CO sc
 WHERE NOT EXISTS (SELECT 1 FROM BINH_LUAN_SU_CO b WHERE b.MA_SC = sc.MA_SC)
 FETCH FIRST 2 ROWS ONLY;

COMMIT;

