SET DEFINE OFF

-- ---- NGUOI_DUNG --------------------------------------------------------
ALTER TABLE NGUOI_DUNG ADD (SDT VARCHAR2(20 CHAR));
ALTER TABLE NGUOI_DUNG ADD (TRANG_THAI VARCHAR2(20 CHAR) DEFAULT 'HOAT_DONG' NOT NULL);
ALTER TABLE NGUOI_DUNG ADD CONSTRAINT CK_NGUOI_DUNG_TRANG_THAI CHECK (TRANG_THAI IN ('HOAT_DONG', 'KHONG_HOAT_DONG'));
ALTER TABLE NGUOI_DUNG ADD (MA_NGUOI_TAO NUMBER);
ALTER TABLE NGUOI_DUNG ADD CONSTRAINT FK_NGUOI_DUNG_NGUOI_TAO FOREIGN KEY (MA_NGUOI_TAO) REFERENCES NGUOI_DUNG (MA_ND);
ALTER TABLE NGUOI_DUNG ADD (NGAY_XOA DATE);
ALTER TABLE NGUOI_DUNG ADD (MA_NGUOI_XOA NUMBER);
ALTER TABLE NGUOI_DUNG ADD CONSTRAINT FK_NGUOI_DUNG_NGUOI_XOA FOREIGN KEY (MA_NGUOI_XOA) REFERENCES NGUOI_DUNG (MA_ND);
CREATE INDEX IDX_NGUOI_DUNG_NGUOI_TAO ON NGUOI_DUNG (MA_NGUOI_TAO);

-- ---- THIET_BI -----------------------------------------------------------
ALTER TABLE THIET_BI ADD (NHA_CUNG_CAP VARCHAR2(150 CHAR));
ALTER TABLE THIET_BI ADD (NGAY_LAP_DAT DATE);
ALTER TABLE THIET_BI ADD (HDSD VARCHAR2(2000 CHAR));

-- ---- PHONG ----------------------------------------------------------------
ALTER TABLE PHONG MODIFY (TANG NULL);

-- ---- PHAN_HOI (bảng mới) ---------------------------------------------------
CREATE TABLE PHAN_HOI (
  MA_PH             NUMBER GENERATED BY DEFAULT AS IDENTITY,
  MA_SC             NUMBER NOT NULL,
  MA_NGUOI_PHAN_HOI NUMBER NOT NULL,
  MUC_HAI_LONG      NUMBER(1) NOT NULL,
  NOI_DUNG          VARCHAR2(1000 CHAR),
  NGAY_PHAN_HOI     DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_PHAN_HOI PRIMARY KEY (MA_PH),
  CONSTRAINT UQ_PHAN_HOI_SU_CO UNIQUE (MA_SC),
  CONSTRAINT FK_PHAN_HOI_SU_CO FOREIGN KEY (MA_SC) REFERENCES SU_CO (MA_SC),
  CONSTRAINT FK_PHAN_HOI_NGUOI FOREIGN KEY (MA_NGUOI_PHAN_HOI) REFERENCES NGUOI_DUNG (MA_ND),
  CONSTRAINT CK_PHAN_HOI_MUC CHECK (MUC_HAI_LONG BETWEEN 1 AND 5)
);
CREATE INDEX IDX_PHAN_HOI_NGUOI ON PHAN_HOI (MA_NGUOI_PHAN_HOI);

-- ---- View sự cố hay gặp (đếm, không lưu cứng để khỏi lệch dữ liệu) --------
CREATE OR REPLACE VIEW V_SU_CO_THUONG_GAP AS
SELECT dm.MA_DM, dm.TEN_DM, COUNT(sc.MA_SC) AS SO_LAN_BAO
  FROM DANH_MUC_SU_CO dm
  LEFT JOIN SU_CO sc ON sc.MA_DM = dm.MA_DM
 GROUP BY dm.MA_DM, dm.TEN_DM;

-- ---- Dữ liệu mẫu nhẹ, an toàn với dữ liệu thật đang có (không dùng ID cố định) --
-- Vài thiết bị/người dùng có thêm SĐT, nhà cung cấp... để demo cột mới có dữ liệu
UPDATE NGUOI_DUNG SET SDT = '0912345678' WHERE MA_ND = (SELECT MIN(MA_ND) FROM NGUOI_DUNG WHERE VAI_TRO = 'ADMIN') AND SDT IS NULL;
UPDATE THIET_BI SET NHA_CUNG_CAP = 'FPT Shop', NGAY_LAP_DAT = DATE '2023-09-01'
 WHERE MA_TB = (SELECT MIN(MA_TB) FROM THIET_BI WHERE LOAI_TB = 'MAY_TINH') AND NHA_CUNG_CAP IS NULL;
-- Văn phòng nhỏ, không cần ghi tầng (minh họa TANG NULL)
UPDATE PHONG SET TANG = NULL WHERE LOAI_PHONG = 'VAN_PHONG';
-- Phản hồi demo cho tối đa 2 sự cố đã HOAN_THANH mà chưa ai phản hồi
INSERT INTO PHAN_HOI (MA_SC, MA_NGUOI_PHAN_HOI, MUC_HAI_LONG, NOI_DUNG)
SELECT sc.MA_SC, sc.MA_NGUOI_BAO, 5, 'Đã xử lý tốt, cảm ơn bộ phận IT.'
  FROM SU_CO sc
 WHERE sc.TRANG_THAI = 'HOAN_THANH'
   AND NOT EXISTS (SELECT 1 FROM PHAN_HOI p WHERE p.MA_SC = sc.MA_SC)
 FETCH FIRST 2 ROWS ONLY;

COMMIT;

