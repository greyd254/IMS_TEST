-- CHẠY BẰNG: SUCO_APP, kết nối vào FREEPDB1
-- MỤC ĐÍCH : tạo 7 bảng. Thứ tự tạo: bảng cha trước, bảng con sau (đúng thứ tự FK).
-- Ghi chú  : dùng "VARCHAR2(n CHAR)" để độ dài tính theo KÝ TỰ, tránh lỗi
--            khi lưu tiếng Việt có dấu (mỗi ký tự có thể chiếm 2-3 byte).
-- =====================================================================
SET DEFINE OFF

-- 1. NGUOI_DUNG: sinh viên, giảng viên, cán bộ và admin (bộ phận IT)
CREATE TABLE NGUOI_DUNG (
  MA_ND     NUMBER GENERATED BY DEFAULT AS IDENTITY,
  HO_TEN    VARCHAR2(100 CHAR) NOT NULL,
  EMAIL     VARCHAR2(100 CHAR) NOT NULL,
  MAT_KHAU  VARCHAR2(200 CHAR) NOT NULL,          -- chuỗi băm PBKDF2 (không lưu mật khẩu gốc), xem MatKhau.java trong web
  DON_VI    VARCHAR2(100 CHAR),
  VAI_TRO   VARCHAR2(10) DEFAULT 'USER' NOT NULL,
  NGAY_TAO  DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_NGUOI_DUNG PRIMARY KEY (MA_ND),
  CONSTRAINT UQ_NGUOI_DUNG_EMAIL UNIQUE (EMAIL),
  CONSTRAINT CK_NGUOI_DUNG_VAI_TRO CHECK (VAI_TRO IN ('USER', 'ADMIN'))
);

-- 2. PHONG: phòng máy, phòng học, văn phòng
CREATE TABLE PHONG (
  MA_PHONG   NUMBER GENERATED BY DEFAULT AS IDENTITY,
  TEN_PHONG  VARCHAR2(100 CHAR) NOT NULL,
  TOA_NHA    VARCHAR2(20 CHAR)  NOT NULL,
  TANG       NUMBER(2) NOT NULL,
  LOAI_PHONG VARCHAR2(20) NOT NULL,
  CONSTRAINT PK_PHONG PRIMARY KEY (MA_PHONG),
  CONSTRAINT CK_PHONG_LOAI CHECK (LOAI_PHONG IN ('PHONG_MAY', 'PHONG_HOC', 'VAN_PHONG'))
);

-- 3. THIET_BI: thiết bị đặt trong phòng (FK -> PHONG)
CREATE TABLE THIET_BI (
  MA_TB      NUMBER GENERATED BY DEFAULT AS IDENTITY,
  TEN_TB     VARCHAR2(150 CHAR) NOT NULL,
  LOAI_TB    VARCHAR2(20) NOT NULL,
  MA_PHONG   NUMBER NOT NULL,
  TINH_TRANG VARCHAR2(20) DEFAULT 'HOAT_DONG' NOT NULL,
  CONSTRAINT PK_THIET_BI PRIMARY KEY (MA_TB),
  CONSTRAINT FK_THIET_BI_PHONG FOREIGN KEY (MA_PHONG) REFERENCES PHONG (MA_PHONG),
  CONSTRAINT CK_THIET_BI_LOAI CHECK (LOAI_TB IN ('MAY_TINH', 'MAY_CHIEU', 'MAY_IN', 'THIET_BI_MANG', 'KHAC')),
  CONSTRAINT CK_THIET_BI_TINH_TRANG CHECK (TINH_TRANG IN ('HOAT_DONG', 'HONG', 'DANG_SUA'))
);

-- 4. DANH_MUC_SU_CO: danh mục dùng chung cho sự cố và bài kinh nghiệm
CREATE TABLE DANH_MUC_SU_CO (
  MA_DM  NUMBER GENERATED BY DEFAULT AS IDENTITY,
  TEN_DM VARCHAR2(100 CHAR) NOT NULL,
  MO_TA  VARCHAR2(500 CHAR),
  CONSTRAINT PK_DANH_MUC_SU_CO PRIMARY KEY (MA_DM),
  CONSTRAINT UQ_DANH_MUC_TEN UNIQUE (TEN_DM)
);

-- 5. BAI_KINH_NGHIEM: kho kinh nghiệm xử lý (FK -> DANH_MUC_SU_CO, NGUOI_DUNG)
CREATE TABLE BAI_KINH_NGHIEM (
  MA_BAI        NUMBER GENERATED BY DEFAULT AS IDENTITY,
  TIEU_DE       VARCHAR2(200 CHAR) NOT NULL,
  MA_DM         NUMBER NOT NULL,
  TRIEU_CHUNG   VARCHAR2(1000 CHAR),
  NGUYEN_NHAN   VARCHAR2(1000 CHAR),
  GIAI_PHAP     VARCHAR2(1000 CHAR) NOT NULL,
  MA_NGUOI_VIET NUMBER NOT NULL,
  NGAY_TAO      DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_BAI_KINH_NGHIEM PRIMARY KEY (MA_BAI),
  CONSTRAINT FK_BAI_KN_DANH_MUC FOREIGN KEY (MA_DM) REFERENCES DANH_MUC_SU_CO (MA_DM),
  CONSTRAINT FK_BAI_KN_NGUOI_VIET FOREIGN KEY (MA_NGUOI_VIET) REFERENCES NGUOI_DUNG (MA_ND)
);

-- 6. SU_CO: bảng trung tâm. MA_ADMIN_XU_LY và MA_TB và MA_BAI_KN cho phép NULL
--    (sự cố mới chưa có admin xử lý; có sự cố không gắn thiết bị, vd: quên mật khẩu).
CREATE TABLE SU_CO (
  MA_SC           NUMBER GENERATED BY DEFAULT AS IDENTITY,
  TIEU_DE         VARCHAR2(200 CHAR) NOT NULL,
  MO_TA           VARCHAR2(1000 CHAR),
  MA_NGUOI_BAO    NUMBER NOT NULL,
  MA_ADMIN_XU_LY  NUMBER,
  MA_TB           NUMBER,
  MA_DM           NUMBER NOT NULL,
  MUC_UU_TIEN     VARCHAR2(20) DEFAULT 'TRUNG_BINH' NOT NULL,
  TRANG_THAI      VARCHAR2(20) DEFAULT 'MOI' NOT NULL,
  NGUYEN_NHAN     VARCHAR2(1000 CHAR),
  CACH_KHAC_PHUC  VARCHAR2(1000 CHAR),
  MA_BAI_KN       NUMBER,
  NGAY_TAO        DATE DEFAULT SYSDATE NOT NULL,
  NGAY_HOAN_THANH DATE,
  CONSTRAINT PK_SU_CO PRIMARY KEY (MA_SC),
  CONSTRAINT FK_SU_CO_NGUOI_BAO FOREIGN KEY (MA_NGUOI_BAO)   REFERENCES NGUOI_DUNG (MA_ND),
  CONSTRAINT FK_SU_CO_ADMIN     FOREIGN KEY (MA_ADMIN_XU_LY) REFERENCES NGUOI_DUNG (MA_ND),
  CONSTRAINT FK_SU_CO_THIET_BI  FOREIGN KEY (MA_TB)          REFERENCES THIET_BI (MA_TB),
  CONSTRAINT FK_SU_CO_DANH_MUC  FOREIGN KEY (MA_DM)          REFERENCES DANH_MUC_SU_CO (MA_DM),
  CONSTRAINT FK_SU_CO_BAI_KN    FOREIGN KEY (MA_BAI_KN)      REFERENCES BAI_KINH_NGHIEM (MA_BAI),
  CONSTRAINT CK_SU_CO_UU_TIEN   CHECK (MUC_UU_TIEN IN ('THAP', 'TRUNG_BINH', 'CAO')),
  CONSTRAINT CK_SU_CO_TRANG_THAI CHECK (TRANG_THAI IN ('MOI', 'DANG_XU_LY', 'HOAN_THANH')),
  CONSTRAINT CK_SU_CO_NGAY_HT   CHECK (NGAY_HOAN_THANH >= NGAY_TAO)
);

-- 7. LICH_SU_XU_LY: nhật ký đổi trạng thái (do trigger ghi, xem file 03)
CREATE TABLE LICH_SU_XU_LY (
  MA_LS             NUMBER GENERATED BY DEFAULT AS IDENTITY,
  MA_SC             NUMBER NOT NULL,
  MA_NGUOI_CAP_NHAT NUMBER,
  TRANG_THAI_CU     VARCHAR2(20),
  TRANG_THAI_MOI    VARCHAR2(20) NOT NULL,
  GHI_CHU           VARCHAR2(500 CHAR),
  THOI_GIAN         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_LICH_SU_XU_LY PRIMARY KEY (MA_LS),
  CONSTRAINT FK_LICH_SU_SU_CO FOREIGN KEY (MA_SC) REFERENCES SU_CO (MA_SC),
  CONSTRAINT FK_LICH_SU_NGUOI FOREIGN KEY (MA_NGUOI_CAP_NHAT) REFERENCES NGUOI_DUNG (MA_ND),
  CONSTRAINT CK_LICH_SU_TT_CU CHECK (TRANG_THAI_CU IN ('MOI', 'DANG_XU_LY', 'HOAN_THANH')),
  CONSTRAINT CK_LICH_SU_TT_MOI CHECK (TRANG_THAI_MOI IN ('MOI', 'DANG_XU_LY', 'HOAN_THANH'))
);

-- Chỉ mục trên các cột hay lọc/JOIN (Oracle không tự tạo index cho FK)
CREATE INDEX IDX_SU_CO_NGUOI_BAO ON SU_CO (MA_NGUOI_BAO);
CREATE INDEX IDX_SU_CO_TRANG_THAI ON SU_CO (TRANG_THAI);
CREATE INDEX IDX_LICH_SU_MA_SC ON LICH_SU_XU_LY (MA_SC);

-- Kiểm tra: phải thấy 7 bảng
SELECT table_name FROM user_tables ORDER BY table_name;
